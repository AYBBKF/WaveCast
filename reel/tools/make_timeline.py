words = SCRIPT.split()
times = [tuple(map(float, x.split('-'))) for x in T.split()]
assert len(words) == len(times) == 122, (len(words), len(times))

# caption groups (inclusive word index ranges), 2-5 words, broken at punctuation
G = [(0,2),(3,4),(5,7),(8,9),(10,12),(13,17),(18,19),(20,22),(23,25),(26,29),(30,32),(33,36),(37,39),(40,42),
     (43,47),(48,50),(51,53),(54,56),(57,60),(61,62),(63,67),(68,71),(72,75),(76,78),(79,81),(82,84),(85,87),
     (88,90),(91,93),(94,98),(99,101),(102,104),(105,108),(109,112),(113,116),(117,121)]
assert G[0][0] == 0 and G[-1][1] == 121 and all(G[i][1] + 1 == G[i+1][0] for i in range(len(G)-1))

groups = []
for i, (a, b) in enumerate(G):
    start = max(0.0, times[a][0] - 0.06)
    nxt = times[G[i+1][0]][0] - 0.06 if i + 1 < len(G) else None
    end = min(nxt, times[b][1] + 0.9) if nxt else times[b][1] + 1.6
    groups.append({'text': ' '.join(words[a:b+1]), 'start': round(start, 2), 'end': round(end, 2), 'n': b - a + 1})

json.dump({'words': [{'w': w, 's': s, 'e': e} for w, (s, e) in zip(words, times)], 'groups': groups},
          open(f'{ROOT}/build/timeline.json', 'w'), ensure_ascii=False, indent=1)
open(f'{ROOT}/build/timeline.js', 'w').write('window.TIMELINE=' + json.dumps({'groups': groups}, ensure_ascii=False) + ';\n')

def ts(x):
    h, r = divmod(x, 3600); m, s = divmod(r, 60)
    return f'{int(h):02d}:{int(m):02d}:{int(s):02d},{int(round((s-int(s))*1000)):03d}'
with open(f'{ROOT}/build/deep_curious_ww3_ar.srt', 'w', encoding='utf-8') as f:
    for i, g in enumerate(groups, 1):
        f.write(f"{i}\n{ts(g['start'])} --> {ts(g['end'])}\n{g['text']}\n\n")
print(len(groups), 'groups; max words', max(g['n'] for g in groups), '; min', min(g['n'] for g in groups))
